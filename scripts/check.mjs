import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import assert from 'node:assert/strict';
const source=await readFile(new URL('../index.html',import.meta.url),'utf8');
const script=source.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(script,'Inline application script exists');
await mkdir(new URL('../test/scratch/',import.meta.url),{recursive:true});
const path=new URL('../test/scratch/application.js',import.meta.url);
await writeFile(path,script);
const result=spawnSync(process.execPath,['--check',path.pathname],{stdio:'inherit'});
assert.equal(result.status,0,'JavaScript syntax');
for (const name of ['description','og:title','og:image']) assert.ok(source.includes(`"${name}"`),name);
assert.ok(source.includes('rel="icon"'),'Favicon');
assert.ok(!/Math\.random\s*\(/.test(script),'Deterministic allocation');
assert.ok(!/<script[^>]+src=/.test(source),'No runtime script dependency');
assert.ok(!/transition\s*:\s*all/.test(source),'Explicit transitions');
const ids=[...source.matchAll(/\bid="([^"]+)"/g)].map(m=>m[1]);
assert.equal(new Set(ids).size,ids.length,'Unique static IDs');
const exported=await readFile(new URL('../dist/index.html',import.meta.url),'utf8');
assert.equal(exported,source,'Production export matches source');
console.log('PASS: JavaScript syntax, metadata, unique IDs, deterministic source, no runtime dependencies, export integrity.');
